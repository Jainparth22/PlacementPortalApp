"""File storage abstraction: local disk | S3-compatible (AWS S3, Cloudflare R2, MinIO...) | Azure Blob.

Why this exists
---------------
Resumes, generated reports and CSV exports used to be written to a local directory and the database
stored *paths*. That breaks as soon as there is more than one machine:
  * the Celery worker that generates a report may run on a different host than the web process that
    serves the download -> "file not found";
  * two web replicas don't see each other's uploads;
  * a redeploy/replace of the container loses the files unless a volume is attached.
Now the app talks to ``Storage`` and the database stores *keys* like ``resumes/resume_3_cv.pdf`` that
mean the same thing on every backend. Pick the backend with ``STORAGE_BACKEND=local|s3|azure``.

Keys are ``<category>/<filename>`` with category in {resumes, reports, exports}. Legacy values already in
the database (absolute paths or ``uploads/resumes/x.pdf``) are still resolved by the local backend, and
``scripts/migrate_storage.py`` moves old files to a cloud backend and rewrites the keys.
"""
import io
import logging
import os
import re
import threading
from pathlib import Path

from flask import Response, current_app, send_file

from config import Config

log = logging.getLogger(__name__)

CATEGORIES = ('resumes', 'reports', 'exports')
_SAFE_KEY = re.compile(r'^(resumes|reports|exports)/[A-Za-z0-9._-]{1,200}$')


def _cfg(key, default=None):
    try:
        return current_app.config.get(key, default)
    except RuntimeError:
        return getattr(Config, key, default)


def validate_key(key):
    """Keys are generated by the app, but validate anyway: no traversal, no odd characters."""
    if not isinstance(key, str) or not _SAFE_KEY.match(key) or '..' in key:
        raise ValueError(f'invalid storage key: {key!r}')
    return key


class Storage:
    name = 'abstract'

    def put_bytes(self, key, data, content_type=None):
        raise NotImplementedError

    def get_bytes(self, key):
        raise NotImplementedError

    def exists(self, key):
        raise NotImplementedError

    def delete(self, key):
        raise NotImplementedError

    def send(self, key, download_name, mimetype=None):
        """Flask response that downloads ``key`` (streamed for remote backends)."""
        raise NotImplementedError

    def healthy(self):
        return True


# --------------------------------------------------------------------------- local disk
class LocalStorage(Storage):
    name = 'local'

    def __init__(self, dirs):
        self.dirs = {cat: Path(p) for cat, p in dirs.items()}
        for p in self.dirs.values():
            p.mkdir(parents=True, exist_ok=True)

    def _path(self, key):
        validate_key(key)
        category, name = key.split('/', 1)
        return self.dirs[category] / name

    def _resolve(self, key):
        """Existing file for ``key``, understanding legacy DB values (absolute / 'uploads/resumes/x.pdf')."""
        if not isinstance(key, str) or not key:
            return None
        if _SAFE_KEY.match(key) and '..' not in key:
            p = self._path(key)
            if p.is_file():
                return p
        base = os.path.basename(key)
        for cat in CATEGORIES:                       # legacy: stored path -> same filename in a category dir
            cand = self.dirs[cat] / base
            if base and cand.is_file():
                return cand
        if os.path.isabs(key) and os.path.isfile(key):
            return Path(key)                         # legacy absolute path written by older versions
        return None

    def put_bytes(self, key, data, content_type=None):
        path = self._path(key)
        tmp = path.with_name(path.name + '.tmp')
        tmp.write_bytes(data)
        os.replace(tmp, path)                        # atomic: readers never see half a file

    def get_bytes(self, key):
        p = self._resolve(key)
        if not p:
            raise FileNotFoundError(key)
        return p.read_bytes()

    def exists(self, key):
        return self._resolve(key) is not None

    def delete(self, key):
        p = self._resolve(key)
        if p:
            p.unlink()

    def send(self, key, download_name, mimetype=None):
        p = self._resolve(key)
        if not p:
            raise FileNotFoundError(key)
        return send_file(p, as_attachment=True, download_name=download_name, mimetype=mimetype)

    def healthy(self):
        return all(os.access(p, os.W_OK) for p in self.dirs.values())


# --------------------------------------------------------------------------- S3-compatible
class S3Storage(Storage):
    name = 's3'

    def __init__(self, bucket, prefix='', endpoint_url=None, region=None, client=None):
        if client is None:
            import boto3                                # lazy: only needed for this backend
            client = boto3.client('s3', endpoint_url=endpoint_url or None, region_name=region or None)
        self.client, self.bucket = client, bucket
        self.prefix = prefix.strip('/') + '/' if prefix and prefix.strip('/') else ''

    def _k(self, key):
        return self.prefix + validate_key(key)

    def put_bytes(self, key, data, content_type=None):
        extra = {'ContentType': content_type} if content_type else {}
        self.client.put_object(Bucket=self.bucket, Key=self._k(key), Body=data, **extra)

    def get_bytes(self, key):
        try:
            return self.client.get_object(Bucket=self.bucket, Key=self._k(key))['Body'].read()
        except self.client.exceptions.NoSuchKey as e:
            raise FileNotFoundError(key) from e

    def exists(self, key):
        try:
            self.client.head_object(Bucket=self.bucket, Key=self._k(key))
            return True
        except Exception as e:  # noqa: BLE001 - botocore ClientError 404
            code = getattr(e, 'response', {}).get('Error', {}).get('Code', '')
            if code in ('404', 'NoSuchKey', 'NotFound'):
                return False
            raise

    def delete(self, key):
        self.client.delete_object(Bucket=self.bucket, Key=self._k(key))

    def send(self, key, download_name, mimetype=None):
        try:
            obj = self.client.get_object(Bucket=self.bucket, Key=self._k(key))
        except self.client.exceptions.NoSuchKey as e:
            raise FileNotFoundError(key) from e
        headers = {'Content-Disposition': f'attachment; filename="{download_name}"'}
        return Response(obj['Body'].iter_chunks(64 * 1024), mimetype=mimetype or obj.get('ContentType', 'application/octet-stream'),
                        headers=headers)

    def healthy(self):
        try:
            self.client.head_bucket(Bucket=self.bucket)
            return True
        except Exception:  # noqa: BLE001
            return False


# --------------------------------------------------------------------------- Azure Blob
class AzureBlobStorage(Storage):
    name = 'azure'

    def __init__(self, container, connection_string=None, account_url=None, client=None):
        if client is None:
            from azure.storage.blob import BlobServiceClient   # lazy import
            if connection_string:
                client = BlobServiceClient.from_connection_string(connection_string)
            else:   # managed identity / workload identity (no secrets in env)
                from azure.identity import DefaultAzureCredential
                client = BlobServiceClient(account_url, credential=DefaultAzureCredential())
        self.container_client = client.get_container_client(container)

    def _blob(self, key):
        return self.container_client.get_blob_client(validate_key(key))

    def put_bytes(self, key, data, content_type=None):
        from azure.storage.blob import ContentSettings
        settings = ContentSettings(content_type=content_type) if content_type else None
        self._blob(key).upload_blob(data, overwrite=True, content_settings=settings)

    def get_bytes(self, key):
        from azure.core.exceptions import ResourceNotFoundError
        try:
            return self._blob(key).download_blob().readall()
        except ResourceNotFoundError as e:
            raise FileNotFoundError(key) from e

    def exists(self, key):
        return self._blob(key).exists()

    def delete(self, key):
        self._blob(key).delete_blob()

    def send(self, key, download_name, mimetype=None):
        from azure.core.exceptions import ResourceNotFoundError
        try:
            stream = self._blob(key).download_blob()
        except ResourceNotFoundError as e:
            raise FileNotFoundError(key) from e
        headers = {'Content-Disposition': f'attachment; filename="{download_name}"'}
        return Response(stream.chunks(), mimetype=mimetype or 'application/octet-stream', headers=headers)

    def healthy(self):
        try:
            return self.container_client.exists()
        except Exception:  # noqa: BLE001
            return False


# --------------------------------------------------------------------------- factory
_instance = None
_lock = threading.Lock()


def build_storage():
    backend = (_cfg('STORAGE_BACKEND', 'local') or 'local').lower()
    if backend == 'local':
        return LocalStorage({
            'resumes': os.path.join(_cfg('UPLOAD_FOLDER'), 'resumes'),
            'reports': _cfg('REPORTS_FOLDER'),
            'exports': _cfg('EXPORTS_FOLDER'),
        })
    if backend == 's3':
        return S3Storage(_cfg('S3_BUCKET'), _cfg('S3_PREFIX', ''), _cfg('S3_ENDPOINT_URL'), _cfg('S3_REGION'))
    if backend == 'azure':
        return AzureBlobStorage(_cfg('AZURE_STORAGE_CONTAINER', 'ppa'), _cfg('AZURE_STORAGE_CONNECTION_STRING'), _cfg('AZURE_STORAGE_ACCOUNT_URL'))
    raise RuntimeError(f'unknown STORAGE_BACKEND {backend!r} (use local, s3 or azure)')


def get_storage():
    global _instance
    if _instance is None:
        with _lock:
            if _instance is None:
                _instance = build_storage()
                log.info('storage_backend', extra={'event': 'storage_backend', 'backend': _instance.name})
    return _instance


def use_storage(storage=None):
    """Inject / reset the storage singleton (tests, scripts)."""
    global _instance
    _instance = storage


def as_stream(data):
    return io.BytesIO(data)
